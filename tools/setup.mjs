// Writes config.js: login check + (optional) GitHub token, both AES-GCM encrypted with a key
// derived from "mobile:password". Nothing secret is stored in plain text.
//
// Usage:  node tools/setup.mjs
// Flags (optional): --mobile 9xxxxxxxxx --password '...' --repo owner/expense-data --vapid <publicKey> --no-token
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import readline from 'node:readline';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG = path.join(ROOT, 'config.js');
const ITERATIONS = 310000;

const args = {};
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (!a.startsWith('--')) continue;
  const k = a.slice(2);
  const next = process.argv[i + 1];
  if (next === undefined || next.startsWith('--')) args[k] = true; else { args[k] = next; i++; }
}

function readConfig() {
  try {
    const src = fs.readFileSync(CONFIG, 'utf8');
    const m = src.match(/window\.APP_CONFIG\s*=\s*(\{[\s\S]*\})\s*;?\s*$/);
    return m ? JSON.parse(m[1]) : {};
  } catch { return {}; }
}

function ask(question, { hidden = false, def = '' } = {}) {
  return new Promise(resolve => {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: true });
    if (hidden) {
      rl._writeToOutput = s => { if (s.includes(question)) process.stdout.write(s); else if (s !== '\r\n' && s !== '\n') process.stdout.write('*'); };
    }
    rl.question(question + (def && !hidden ? ` [${def}]` : '') + ': ', ans => {
      rl.close();
      if (hidden) process.stdout.write('\n');
      resolve(ans.trim() || def);
    });
  });
}

const b64 = buf => Buffer.from(buf).toString('base64');
async function encryptor(mobile, password, salt) {
  const base = await crypto.subtle.importKey('raw', new TextEncoder().encode(`${mobile}:${password}`), 'PBKDF2', false, ['deriveKey']);
  const key = await crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
  return async text => {
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(text));
    return { iv: b64(iv), ct: b64(ct) };
  };
}

const cfg = readConfig();
const mobile = String(args.mobile || await ask('Login mobile number')).replace(/\D/g, '');
if (mobile.length !== 10) { console.error('Mobile number must be 10 digits'); process.exit(1); }
const password = String(args.password || await ask('Login password', { hidden: true }));
if (!password) { console.error('Password is required'); process.exit(1); }
const dataRepo = String('repo' in args ? args.repo : await ask('Private data repo (owner/name)', { def: cfg.dataRepo || '' }));
const vapidPublicKey = String(args.vapid || cfg.vapidPublicKey || '');
let token = '';
if (!args['no-token']) token = String(args.token || await ask('GitHub fine-grained token for the data repo (Enter = skip, local mode)', { hidden: true }));

if (token) {
  if (!/^(github_pat_|ghp_)/.test(token)) {
    console.error('\nThat does not look like a GitHub token (it should start with "github_pat_"). Copy it again with the "Copy token" button.');
    process.exit(1);
  }
  const r = await fetch(`https://api.github.com/repos/${dataRepo}/contents/`, { headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' } });
  if (!r.ok) {
    console.error(`\nGitHub rejected the token for ${dataRepo} (HTTP ${r.status}). Nothing was changed. Copy the token again and retry.`);
    process.exit(1);
  }
  console.log(`Token checked: it can access ${dataRepo}.`);
}

const salt = crypto.getRandomValues(new Uint8Array(16));
const encrypt = await encryptor(mobile, password, salt);
const out = {
  dataRepo,
  vapidPublicKey,
  auth: {
    salt: b64(salt),
    iterations: ITERATIONS,
    check: await encrypt('expense-tracker-ok'),
    token: token ? await encrypt(token) : null,
  },
};
fs.writeFileSync(CONFIG, `// Generated by tools/setup.mjs — safe to publish (secrets are encrypted with your login).\nwindow.APP_CONFIG = ${JSON.stringify(out, null, 2)};\n`);
console.log(`\nconfig.js written. Mode: ${token ? 'GitHub sync (' + dataRepo + ')' : 'local only (no token)'}.`);
